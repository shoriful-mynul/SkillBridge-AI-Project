import { PDFParse } from 'pdf-parse';

export interface PdfExtractionResult {
  success: boolean;
  text?: string;
  pageCount?: number;
  error?: string;
  isScannedOrEmpty?: boolean;
}

const MAX_PDF_BYTES = 5 * 1024 * 1024; // 5 MB

/**
 * Extracts readable text from a text-based PDF buffer.
 * Validates file size, PDF header magic bytes, and readable content.
 * Never logs or retains the buffer.
 */
export async function extractTextFromPdfBuffer(
  buffer: Buffer,
  fileName: string = 'document.pdf'
): Promise<PdfExtractionResult> {
  // 1. Enforce 5 MB limit
  if (buffer.length > MAX_PDF_BYTES) {
    return {
      success: false,
      error: `File "${fileName}" exceeds the 5 MB limit (${(buffer.length / (1024 * 1024)).toFixed(2)} MB). Please upload a smaller file.`,
    };
  }

  // 2. Validate PDF magic bytes (%PDF-)
  const magic = buffer.subarray(0, 5).toString('ascii');
  if (!magic.startsWith('%PDF-')) {
    return {
      success: false,
      error: `File "${fileName}" is not a valid PDF document. Please upload a standard PDF.`,
    };
  }

  // 3. Extract text
  let parser: InstanceType<typeof PDFParse> | null = null;
  try {
    parser = new PDFParse({ data: buffer });
    const data = await parser.getText();
    const rawText = data?.text || '';
    // Strip page numbering artifacts generated by parser (e.g. "-- 1 of 2 --")
    const cleanedText = rawText
      .replace(/-- \d+ of \d+ --/g, '')
      .replace(/\r\n/g, '\n')
      .trim();

    // 4. Check if text is scanned, encrypted, or empty
    if (cleanedText.length < 25) {
      return {
        success: false,
        isScannedOrEmpty: true,
        error:
          'This PDF appears to be scanned, image-based, or encrypted without selectable text. Please paste your project text directly or use an export with selectable text.',
      };
    }

    return {
      success: true,
      text: cleanedText,
      pageCount: data?.total || 1,
    };
  } catch (err: any) {
    const msg = err?.message || 'Failed to parse PDF document.';
    if (msg.includes('password') || msg.includes('encrypted') || msg.includes('PasswordException')) {
      return {
        success: false,
        error: 'This PDF is password-protected or encrypted. Please upload an unprotected PDF or paste your project text.',
      };
    }
    return {
      success: false,
      error: `Unable to extract text from PDF: ${msg}. You can paste your text directly instead.`,
    };
  } finally {
    if (parser) {
      try {
        await parser.destroy();
      } catch {
        // ignore cleanup errors
      }
    }
  }
}
